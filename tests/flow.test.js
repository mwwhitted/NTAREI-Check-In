import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { JSDOM } from 'jsdom';
import { IDBFactory } from 'fake-indexeddb';
import { getAllRecords, putRecord, _resetConnectionForTests } from '../src/db.js';
import { recordsToCsv } from '../src/export.js';

test('review/edit/finish, incomplete export exclusion, and isolated read-only staff lookup', async () => {
  const dom = new JSDOM(await readFile(new URL('../index.html', import.meta.url), 'utf8'), {
    url: 'http://localhost/', pretendToBeVisual: true,
  });
  globalThis.window = dom.window;
  globalThis.document = dom.window.document;
  globalThis.indexedDB = new IDBFactory();
  globalThis.requestAnimationFrame = fn => fn();
  globalThis.ResizeObserver = class { observe() {} };
  dom.window.scrollTo = () => {};
  _resetConnectionForTests();
  await import('../src/app.js');
  const el = id => document.getElementById(id);
  const flush = async () => { for (let i = 0; i < 10; i++) await new Promise(resolve => setTimeout(resolve, 0)); };
  assert.equal(el('meeting-setup').hidden, false);
  el('meeting-name').value = 'October Meeting';
  el('meeting-form').dispatchEvent(new dom.window.Event('submit', { cancelable: true }));
  const submit = () => el('attendee-form').dispatchEvent(new dom.window.Event('submit', { cancelable: true }));
  submit();
  await flush();
  assert.equal((await getAllRecords()).length, 0);
  assert.equal(el('handoff-view').hidden, true);

  for (const [id, value] of Object.entries({ 'first-name': 'Alex', 'last-name': 'O’Brien', email: 'alex@example.com', zip: '75001' })) el(id).value = value;
  el('first-time').checked = true;
  el('source-other-radio').checked = true;
  el('source-other-radio').dispatchEvent(new dom.window.Event('change'));
  el('source-other-text').value = 'A friend, "Sam"';
  submit();
  await flush();
  assert.equal(el('handoff-view').hidden, false);
  assert.equal(el('handoff-source').textContent, 'Other — A friend, "Sam"');
  assert.equal(recordsToCsv(await getAllRecords()).split('\r\n').filter(Boolean).length, 1);
  el('edit-btn').click();
  assert.equal(el('first-name').value, 'Alex');
  assert.equal(el('last-name').value, 'O’Brien');
  assert.equal(el('email').value, 'alex@example.com');
  assert.equal(el('zip').value, '75001');
  assert.equal(el('first-time').checked, true);
  assert.equal(el('source-other-radio').checked, true);
  assert.equal(el('source-other-text').value, 'A friend, "Sam"');
  assert.equal(el('source-other-text').disabled, false);
  el('first-name').value = 'Alexandra';
  submit();
  el('finished-btn').click();
  el('finished-btn').click();
  await flush();
  const saved = await getAllRecords();
  assert.equal(saved.length, 1);
  assert.equal(saved[0].first_name, 'Alexandra');
  assert.equal(el('completion-view').hidden, false);
  assert.equal(el('handoff-view').hidden, true);
  assert.ok(saved[0].created_at);
  assert.match(recordsToCsv(saved), /Alexandra/);
  el('next-attendee-btn').click();
  assert.equal(el('first-name').value, '');
  assert.equal(el('first-time').checked, false);
  assert.equal(el('source-other-radio').checked, false);
  assert.equal(el('source-other-text').value, '');

  await putRecord({ ...saved[0], record_id: 'another', first_name: '<script>Sam</script>', email: 'sam@example.com' });
  const yesterday = new Date(); yesterday.setDate(yesterday.getDate() - 1);
  await putRecord({ ...saved[0], record_id: 'old', meeting_id: 'other-meeting', created_at: yesterday.toISOString(), first_name: 'Yesterday' });
  const before = await getAllRecords();
  el('first-name').value = 'Unsaved draft';
  el('staff-panel').open = true;
  el('tonight-btn').click();
  await flush();
  assert.equal(el('tonight-list').children.length, 2);
  el('registration-search').value = 'sam@example.com';
  el('registration-search').dispatchEvent(new dom.window.Event('input'));
  assert.equal(el('tonight-list').children.length, 1);
  el('tonight-list').querySelector('button').click();
  assert.match(el('tonight-details').textContent, /<script>Sam<\/script>/);
  assert.equal(el('tonight-details').querySelector('script'), null);
  assert.equal(el('tonight-details').querySelector('input,button'), null);
  assert.equal(el('first-name').value, 'Unsaved draft');
  assert.deepEqual(await getAllRecords(), before);
  el('registration-search').value = 'alexandra';
  el('registration-search').dispatchEvent(new dom.window.Event('input'));
  el('tonight-list').querySelector('button').click();
  assert.match(el('tonight-details').textContent, /Alexandra/);
  el('last-entry-btn').click();
  await flush();
  assert.equal(el('last-entry-details').hidden, false);
  el('staff-panel').open = false;
  await flush();
  assert.equal(el('tonight-panel').hidden, true);
  assert.equal(el('tonight-details').textContent, '');

  // Geometry-based cue: visible above form end, hidden at its end and on review.
  el('attendee-form').getBoundingClientRect = () => ({ bottom: 2000 });
  window.dispatchEvent(new dom.window.Event('scroll'));
  assert.equal(el('scroll-cue').hidden, false);
  el('attendee-form').getBoundingClientRect = () => ({ bottom: 100 });
  window.dispatchEvent(new dom.window.Event('scroll'));
  assert.equal(el('scroll-cue').hidden, true);
  dom.window.close();
});
