import { test, expect } from '@playwright/test';

test('tablet flow works after offline reload, preserves edits and saved CSV data', async ({ page, context }) => {
  await page.goto('/');
  await page.evaluate(async () => {
    await navigator.serviceWorker.ready;
    if (!navigator.serviceWorker.controller) await new Promise(resolve => navigator.serviceWorker.addEventListener('controllerchange', resolve, { once: true }));
  });
  await expect(page.locator('#meeting-setup')).toBeVisible();
  await page.locator('#meeting-name').fill('October Main Meeting');
  await page.getByRole('button', { name: 'Start Meeting', exact: true }).click();
  await context.setOffline(true);
  await page.reload();
  await expect(page.locator('#meeting-setup')).toBeHidden();
  await expect(page.locator('#current-meeting')).toHaveText('Meeting: October Main Meeting');
  await expect(page.getByText('MORE QUESTIONS BELOW')).toBeVisible();
  await page.locator('#first-name').fill('Offline');
  await page.locator('#last-name').fill('Guest');
  await page.locator('#email').fill('offline@example.com');
  await page.locator('#zip').fill('75001');
  await page.locator('#first-time').check();
  await page.locator('#source-other-radio').check();
  await page.locator('#source-other-text').fill('A friend, "Pat"');
  await page.getByRole('button', { name: 'REVIEW MY INFORMATION' }).scrollIntoViewIfNeeded();
  await expect(page.locator('#scroll-cue')).toBeHidden();
  await page.getByRole('button', { name: 'REVIEW MY INFORMATION' }).click();
  await page.locator('#staff-panel > summary').click();
  await expect(page.locator('#record-count')).toHaveText('0');
  await page.locator('#staff-panel > summary').click();
  await page.locator('#edit-btn').click();
  await expect(page.locator('#first-name')).toHaveValue('Offline');
  await expect(page.locator('#source-other-text')).toHaveValue('A friend, "Pat"');
  await expect(page.locator('#first-time')).toBeChecked();
  await page.locator('#first-name').fill('Edited');
  await page.getByRole('button', { name: 'REVIEW MY INFORMATION' }).click();
  await page.locator('#finished-btn').click();
  await expect(page.locator('#completion-view')).toContainText('Please hand this tablet to the staff.');
  await page.locator('#next-attendee-btn').click();
  await expect(page.locator('#first-name')).toHaveValue('');
  await page.reload();
  await page.locator('#staff-panel > summary').click();
  await expect(page.locator('#record-count')).toHaveText('1');
  await page.locator('#tonight-btn').click();
  await page.locator('#registration-search').fill('offline@example.com');
  await page.locator('#tonight-list button').click();
  await expect(page.locator('#tonight-details')).toContainText('Edited Guest');
  await expect(page.locator('#tonight-details input')).toHaveCount(0);
  await page.locator('#last-entry-btn').click();
  await expect(page.locator('#last-entry-name')).toHaveText('Edited Guest');
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#export-csv-btn').click();
  const download = await downloadPromise;
  const stream = await download.createReadStream();
  let csv = ''; for await (const chunk of stream) csv += chunk.toString();
  expect(csv).toContain('Edited,Guest,offline@example.com,75001,Yes,Other,"A friend, ""Pat"""');
});

test('meeting setup is required, persists across midnight, and isolates subsequent meetings', async ({ page }) => {
  await page.clock.setFixedTime(new Date('2026-10-31T23:55:00'));
  await page.goto('/');
  await expect(page.locator('#meeting-setup')).toBeVisible();
  await expect(page.locator('#attendee-view')).toBeHidden();
  await page.locator('#meeting-name').fill('   ');
  await page.getByRole('button', { name: 'Start Meeting', exact: true }).click();
  await expect(page.locator('#meeting-error')).toContainText('Please enter');
  await page.locator('#meeting-name').fill('October, "Main Meeting"');
  await page.getByRole('button', { name: 'Start Meeting', exact: true }).click();
  const original = await page.evaluate(() => JSON.parse(localStorage.getItem('ntarei-active-meeting')));
  const checkIn = async (name) => {
    await page.locator('#first-name').fill(name);
    await page.locator('#last-name').fill('Guest');
    await page.locator('#email').fill(`${name}@example.com`);
    await page.locator('#zip').fill('75001');
    await page.getByRole('radio', { name: 'Facebook', exact: true }).check();
    await page.getByRole('button', { name: 'REVIEW MY INFORMATION' }).click();
    await page.locator('#finished-btn').click();
    await expect(page.locator('#completion-view')).toBeVisible();
    await page.locator('#next-attendee-btn').click();
  };
  await checkIn('Before');
  await page.clock.setFixedTime(new Date('2026-11-01T00:15:00'));
  await page.reload();
  await expect(page.locator('#meeting-setup')).toBeHidden();
  await checkIn('After');
  await page.locator('#staff-panel > summary').click();
  await page.locator('#tonight-btn').click();
  await expect(page.locator('#tonight-list button')).toHaveCount(2);
  await page.locator('#staff-panel > summary').click();
  await page.locator('#first-name').fill('Draft');
  await page.locator('#staff-panel > summary').click();
  await page.locator('#new-meeting-btn').click();
  await expect(page.locator('#meeting-setup')).toBeHidden();
  await expect(page.locator('#first-name')).toHaveValue('Draft');
  await page.locator('#first-name').fill('');
  await page.locator('#new-meeting-btn').click();
  await expect(page.locator('#meeting-name')).toHaveValue('');
  await page.locator('#meeting-cancel').click();
  await expect(page.locator('#current-meeting')).toContainText(original.name);
  await page.locator('#staff-panel > summary').click();
  await page.locator('#new-meeting-btn').click();
  await page.locator('#meeting-name').fill(original.name);
  await page.getByRole('button', { name: 'Start Meeting', exact: true }).click();
  const next = await page.evaluate(() => JSON.parse(localStorage.getItem('ntarei-active-meeting')));
  expect(next.id).not.toBe(original.id);
  await page.locator('#staff-panel > summary').click();
  await page.locator('#tonight-btn').click();
  await expect(page.locator('#tonight-list button')).toHaveCount(0);
  const saved = await page.evaluate(async () => (await import('/src/db.js')).getAllRecords());
  expect(saved).toHaveLength(2);
  expect(saved.every(r => r.meeting_id === original.id && r.meeting_name === original.name)).toBe(true);
  await page.evaluate(() => localStorage.setItem('ntarei-active-meeting', JSON.stringify({ id: 'broken', name: ' ' })));
  await page.reload();
  await expect(page.locator('#meeting-setup')).toBeVisible();
});

test('scroll cue follows the visible viewport above a simulated keyboard', async ({ page }) => {
  // Desktop automation cannot open an Android keyboard. Model its visual
  // viewport resize and pan while leaving the layout viewport unchanged.
  await page.addInitScript(() => {
    const viewport = new EventTarget();
    viewport.height = innerHeight;
    viewport.offsetTop = 0;
    Object.defineProperty(window, 'visualViewport', { value: viewport });
  });
  await page.goto('/');
  await page.locator('#meeting-name').fill('Keyboard test');
  await page.getByRole('button', { name: 'Start Meeting', exact: true }).click();
  await page.locator('#email').focus();
  await page.evaluate(() => {
    visualViewport.height = 520;
    visualViewport.dispatchEvent(new Event('resize'));
  });
  const cue = page.locator('#scroll-cue');
  await expect(cue).toBeVisible();
  let bounds = await cue.boundingBox();
  expect(Math.round(bounds.y + bounds.height)).toBe(520);
  await page.evaluate(() => {
    visualViewport.offsetTop = 40;
    visualViewport.dispatchEvent(new Event('scroll'));
  });
  bounds = await cue.boundingBox();
  expect(Math.round(bounds.y + bounds.height)).toBe(560);
  await page.evaluate(() => {
    visualViewport.height = innerHeight;
    visualViewport.offsetTop = 0;
    visualViewport.dispatchEvent(new Event('resize'));
  });
  bounds = await cue.boundingBox();
  expect(Math.round(bounds.y + bounds.height)).toBe(1024);
  await page.getByRole('button', { name: 'REVIEW MY INFORMATION' }).scrollIntoViewIfNeeded();
  await expect(cue).toBeHidden();
});
